const has = (c: ProjectConfig, id: string) =>
  c.modules.includes(id as ProjectConfig["modules"][number]);

const pad = (value: string, width: number) => value.padEnd(width, " ");

function renderModel(model: ModelDef): string {
  const name = pascalCase(model.name);
  const rows = [
    { key: "id", type: "String", attrs: "@id @default(cuid())" },
    ...model.fields.map((f) => ({
      key: camelCase(f.name),
      type: `${f.type}${f.list ? "[]" : ""}${f.optional && !f.list ? "?" : ""}`,
      attrs: [
        f.unique ? "@unique" : "",
        f.name === "createdAt" ? "@default(now())" : "",
        f.name === "updatedAt" ? "@updatedAt" : "",
      ]
        .filter(Boolean)
        .join(" "),
    })),
    { key: "updatedAt", type: "DateTime", attrs: "@updatedAt" },
  ];
  const keyWidth = Math.max(...rows.map((r) => r.key.length)) + 1;
  const typeWidth = Math.max(...rows.map((r) => r.type.length)) + 1;
  const body = rows
    .map(
      (r) =>
        `  ${pad(r.key, keyWidth)}${pad(r.type, typeWidth)}${r.attrs}`.trimEnd(),
    )
    .join("\n");
  return `model ${name} {\n${body}\n\n  @@map("${camelCase(name)}s")\n}`;
}

function prismaSchema(c: ProjectConfig): string {
  const models = c.models.map(renderModel).join("\n\n");
  const session = has(c, "auth")
    ? `\n\nmodel Session {\n  id        String   @id @default(cuid())\n  token     String   @unique\n  userId    String\n  expiresAt DateTime\n  createdAt DateTime @default(now())\n\n  @@index([userId])\n  @@map("sessions")\n}`
    : "";
  return `// Generated by Forge — edit freely, this is your code.
generator client {
  provider = "prisma-client-js"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

${models}${session}
`;
}

