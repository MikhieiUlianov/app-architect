export function buildTree(files: GeneratedFile[]): TreeNode[] {
  const root: TreeNode[] = [];

  for (const file of files) {
    const segments = file.path.split("/");
    let level = root;
    let prefix = "";
    segments.forEach((segment, index) => {
      prefix = prefix ? `${prefix}/${segment}` : segment;
      const isFile = index === segments.length - 1;
      let node = level.find((n) => n.name === segment && n.path === prefix);
      if (!node) {
        node = {
          name: segment,
          path: prefix,
          kind: isFile ? "file" : "dir",
          ...(isFile ? {} : { children: [] }),
        };
        level.push(node);
      }
      if (!isFile) level = node.children!;
    });
  }

  const sort = (nodes: TreeNode[]): TreeNode[] =>
    nodes
      .map((n) => (n.children ? { ...n, children: sort(n.children) } : n))
      .sort((a, b) =>
        a.kind === b.kind
          ? a.name.localeCompare(b.name)
          : a.kind === "dir"
            ? -1
            : 1,
      );

  return sort(root);
}

export interface Issue {
  level: "error" | "warning";
  message: string;
}

export function validateConfig(c: ProjectConfig): Issue[] {
  const issues: Issue[] = [];
  if (!c.name.trim()) issues.push({ level: "error", message: "Project name is required" });
  if (c.port < 1 || c.port > 65535)
    issues.push({ level: "error", message: "Port must be between 1 and 65535" });
  if (c.models.length === 0)
    issues.push({ level: "warning", message: "No data models — the schema will be empty" });

  const seen = new Set<string>();
  for (const model of c.models) {
    const name = pascalCase(model.name);
    if (seen.has(name))
      issues.push({ level: "error", message: `Duplicate model name "${name}"` });
    seen.add(name);

    const fieldNames = new Set<string>();
    for (const field of model.fields) {
      const fname = camelCase(field.name);
      if (["id", "updatedAt"].includes(fname))
        issues.push({
          level: "warning",
          message: `${name}.${fname} is generated automatically and will be ignored`,
        });
      if (fieldNames.has(fname))
        issues.push({
          level: "error",
          message: `Duplicate field "${fname}" on ${name}`,
        });
      fieldNames.add(fname);
    }
  }
  return issues;
}

export function estimateBytes(files: GeneratedFile[]): number {
  return files.reduce((sum, f) => sum + f.contents.length, 0);
}
